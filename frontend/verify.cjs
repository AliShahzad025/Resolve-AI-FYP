const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs=require('fs');
async function main(){
  const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL || 'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1080},deviceScaleFactor:1,reducedMotion:'reduce'});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  fs.mkdirSync('screenshots',{recursive:true});
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5174/');
  await page.evaluate(()=>localStorage.clear());await page.reload();
  await page.getByRole('heading',{name:'Your store, at a glance.'}).waitFor();
  await page.screenshot({path:'screenshots/01-overview.png',fullPage:true});
  await page.getByRole('link',{name:'Orders & risk'}).click();
  await page.getByLabel('Search orders').fill('Ayesha');
  if(await page.locator('tbody tr').count()!==1)throw new Error('Order filter failed');
  await page.getByLabel('Search orders').fill('');
  await page.screenshot({path:'screenshots/02-orders.png',fullPage:true});
  await page.getByLabel('Review order 1048').click();
  await page.getByRole('heading',{name:'Order #1048'}).waitFor();
  await page.screenshot({path:'screenshots/03-order-detail.png',fullPage:true});
  await page.getByLabel('Close order details').click();
  await page.getByRole('link',{name:/Complaints/}).click();
  await page.screenshot({path:'screenshots/04-complaints.png',fullPage:true});
  await page.getByLabel('Response draft').fill('Thank you, Ayesha. Our support team is reviewing your order.');
  await page.getByRole('button',{name:'Approve & send'}).click();
  await page.getByText('Thank you, Ayesha. Our support team is reviewing your order.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Mark resolved'}).click();
  await page.getByRole('button',{name:'Reopen case'}).waitFor();
  await page.getByRole('button',{name:'Reopen case'}).click();
  await page.getByRole('link',{name:'Policy library'}).click();
  await page.screenshot({path:'screenshots/05-policies.png',fullPage:true});
  const content=await page.getByLabel('Policy content').inputValue();
  await page.getByLabel('Policy content').fill(content+'\n\nTest revision for verification.');
  await page.getByRole('button',{name:'Save new version'}).click();
  await page.getByRole('button',{name:'Activate version'}).click();
  await page.getByRole('link',{name:'Settings',exact:true}).click();
  await page.screenshot({path:'screenshots/06-integrations.png',fullPage:true});
  await page.getByRole('tab',{name:'Team members'}).click();
  await page.screenshot({path:'screenshots/07-team.png',fullPage:true});
  await page.getByRole('button',{name:'Add member'}).click();
  await page.getByLabel('Full name',{exact:true}).fill('Test Agent');
  await page.getByLabel('Email address').fill('agent@example.com');
  await page.getByRole('dialog').getByRole('button',{name:'Add member'}).click();
  await page.getByText('Test Agent',{exact:true}).waitFor();
  await page.getByRole('tab',{name:'Routing rules'}).click();
  await page.screenshot({path:'screenshots/08-routing.png',fullPage:true});
  await page.getByRole('switch',{name:'Automatic policy replies'}).click();
  await page.getByRole('button',{name:'Save rules'}).click();
  await page.reload();
  await page.getByRole('tab',{name:'Routing rules'}).click();
  if(await page.getByRole('switch',{name:'Automatic policy replies'}).getAttribute('aria-checked')!=='true')throw new Error('Settings persistence failed');
  await page.getByLabel('Sign out').click();
  await page.screenshot({path:'screenshots/09-sign-in.png',fullPage:true});
  await page.getByRole('button',{name:'Create an account'}).click();
  await page.screenshot({path:'screenshots/10-sign-up.png',fullPage:true});
  await page.getByRole('button',{name:'Open sample workspace'}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'screenshots/11-mobile-overview.png',fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile page overflow');
  await page.getByLabel('Open navigation').click();
  await page.getByRole('link',{name:/Complaints/}).click();
  await page.getByRole('button',{name:/Ayesha Khan/}).click();
  await page.screenshot({path:'screenshots/12-mobile-case.png',fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile case overflow');
  await page.evaluate(()=>localStorage.clear());
  await browser.close();
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('PASS: navigation, filtering, order detail, reply approval, case resolution, policy version activation, staff creation, persistent routing settings, auth screens, mobile layout; no browser errors.');
}
main().catch(e=>{console.error(e);process.exit(1)});
